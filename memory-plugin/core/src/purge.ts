// 终版 WP2 — pattern purge.
//
// A normal forget deletes by entry id. A leaked secret needs the other
// shape: "remove this fragment from every copy". This module only
// SCANS and MASKS; the Core method does the rewriting and the audit.
//
// Snapshots are the awkward part. A pre-delete snapshot is a complete
// copy of the old words, so a partial rewrite of its JSON stores is
// easy to get wrong. The rule here is stricter and simpler: a snapshot
// that contains the pattern is DELETED as a whole and recorded as
// removed. The user loses that restore point; they keep the guarantee
// that the secret is not lying in a snapshot.
//
// MEMORY.md, monthly archives and the diary are skill-owned — the
// plugin never rewrites them. They are reported as external copies so
// the operator knows to handle them.

import { existsSync, readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import type { MemoryEntry } from "./types.ts";

export interface PurgeMatch {
  id: string;
  date: string;
  time: string;
  role: string;
  kind: string;
  /** The match with the pattern replaced by `***` — never the secret. */
  masked: string;
}

export interface PurgeScan {
  matches: PurgeMatch[];
  /** Snapshot directory names that contain the pattern. */
  snapshots: string[];
  /** Skill-owned files that still contain it (never rewritten). */
  externalFiles: string[];
}

export interface PurgeResult {
  ok: boolean;
  dryRun: boolean;
  patternLength: number;
  matches: PurgeMatch[];
  snapshots: string[];
  snapshotsRemoved: string[];
  externalFiles: string[];
  removed: number;
}

/** Show at most 2 chars on each side of the match; the match itself
 *  is always `***`. */
export function maskAround(text: string, pattern: string): string {
  const at = text.indexOf(pattern);
  if (at < 0) return "";
  const before = text.slice(Math.max(0, at - 2), at);
  const after = text.slice(
    at + pattern.length,
    Math.min(text.length, at + pattern.length + 2),
  );
  return `${before}***${after}`;
}

export function scanEntries(
  entries: MemoryEntry[],
  pattern: string,
): PurgeMatch[] {
  const out: PurgeMatch[] = [];
  for (const entry of entries) {
    if (typeof entry.text !== "string" || !entry.text.includes(pattern)) {
      continue;
    }
    out.push({
      id: entry.id,
      date: entry.date,
      time: entry.time,
      role: entry.role,
      kind: entry.kind ?? "persona",
      masked: maskAround(entry.text, pattern),
    });
  }
  return out;
}

function walkFiles(dir: string): string[] {
  const out: string[] = [];
  let names: string[];
  try {
    names = readdirSync(dir);
  } catch {
    return out;
  }
  for (const name of names) {
    const full = join(dir, name);
    let isDir = false;
    try {
      // A directory read throws for files; keep it cheap and simple.
      readdirSync(full);
      isDir = true;
    } catch {
      isDir = false;
    }
    if (isDir) out.push(...walkFiles(full));
    else out.push(full);
  }
  return out;
}

/** Snapshot dirs that contain the pattern in any text file. */
export function scanSnapshots(dataDir: string, pattern: string): string[] {
  const root = join(dataDir, ".snapshots");
  if (!existsSync(root)) return [];
  const out: string[] = [];
  let names: string[];
  try {
    names = readdirSync(root);
  } catch {
    return [];
  }
  for (const name of names) {
    const dir = join(root, name);
    let hit = false;
    for (const file of walkFiles(dir)) {
      try {
        if (readFileSync(file, "utf8").includes(pattern)) {
          hit = true;
          break;
        }
      } catch {
        // Binary / unreadable file: skip.
      }
    }
    if (hit) out.push(name);
  }
  return out;
}

const EXTERNAL_NAMES = /^(MEMORY\.md|MEMORY-\d{4}-\d{2}\.md)$/;

/** Skill-owned files that still contain the pattern. The diary is
 *  encrypted and never scanned; the starmap is derived and will be
 *  regenerated by the purge, so it is not reported. */
export function scanExternalFiles(
  dataDir: string,
  pattern: string,
): string[] {
  const out: string[] = [];
  for (const name of readdirSync(dataDir)) {
    if (!EXTERNAL_NAMES.test(name)) continue;
    try {
      if (readFileSync(join(dataDir, name), "utf8").includes(pattern)) {
        out.push(name);
      }
    } catch {
      // Unreadable: cannot prove it is clean, but do not claim it is dirty.
    }
  }
  return out;
}

export function scanPattern(
  dataDir: string,
  entries: MemoryEntry[],
  pattern: string,
  includeSnapshots = true,
): PurgeScan {
  return {
    matches: scanEntries(entries, pattern),
    snapshots: includeSnapshots ? scanSnapshots(dataDir, pattern) : [],
    externalFiles: scanExternalFiles(dataDir, pattern),
  };
}
